USE DATABASE NESA_EDUCATION;
USE SCHEMA STAGING;

-- 1. Row counts
SELECT 'CSR RAW' AS table_name, COUNT(*) AS row_count FROM NESA_EDUCATION.RAW.CSR_EDUCATION_DATA
UNION ALL
SELECT 'CSR STAGING_RAW', COUNT(*) FROM NESA_EDUCATION.STAGING.CSR_EDUCATION_STAGING_RAW
UNION ALL
SELECT 'CSR CLEAN', COUNT(*) FROM NESA_EDUCATION.STAGING.CSR_EDUCATION_DATA_CLEAN
UNION ALL
SELECT 'NESA RAW', COUNT(*) FROM NESA_EDUCATION.RAW.NESA_SOURCE_DATA
UNION ALL
SELECT 'NESA STAGING_RAW', COUNT(*) FROM NESA_EDUCATION.STAGING.NESA_SOURCE_STAGING_RAW
UNION ALL
SELECT 'NESA CLEAN', COUNT(*) FROM NESA_EDUCATION.STAGING.NESA_SOURCE_DATA_CLEAN;

-- 2. Null check (CSR)
SELECT
    SUM(CASE WHEN country IS NULL THEN 1 ELSE 0 END) AS null_country,
    SUM(CASE WHEN potential_nominee IS NULL THEN 1 ELSE 0 END) AS null_nominee
FROM NESA_EDUCATION.STAGING.CSR_EDUCATION_DATA_CLEAN;

-- 3. Null check (NESA)
SELECT
    SUM(CASE WHEN nominee_name IS NULL THEN 1 ELSE 0 END) AS null_nominee_name,
    SUM(CASE WHEN region_name IS NULL THEN 1 ELSE 0 END) AS null_region
FROM NESA_EDUCATION.STAGING.NESA_SOURCE_DATA_CLEAN;

-- 4. Lineage check
SELECT COUNT(*) AS missing_lineage_csr
FROM NESA_EDUCATION.STAGING.CSR_EDUCATION_DATA_CLEAN
WHERE source_record_id IS NULL;

SELECT COUNT(*) AS missing_lineage_nesa
FROM NESA_EDUCATION.STAGING.NESA_SOURCE_DATA_CLEAN
WHERE source_record_id IS NULL;